// Copies the print agent's source files (../print-agent) into src/utils/agentFiles.generated.ts so the server can offer
// them as a download (Printers & Stations -> Download). The Docker build only has ./server, so the files travel inside
// the code. Run after changing anything in print-agent:   npm run sync:agent
// tests/agentFiles.test.ts fails when this file is out of date.
const fs = require("fs");
const path = require("path");

const FILES = ["agent.js", "agent.d.ts", "package.json", "setup-ui.html", "README.md"];
const source = path.join(__dirname, "..", "..", "print-agent");
const target = path.join(__dirname, "..", "src", "utils", "agentFiles.generated.ts");

const files = {};
for (const name of FILES) files[name] = fs.readFileSync(path.join(source, name), "utf8");

fs.writeFileSync(
  target,
  `// Generated by scripts/sync-agent.js from ../print-agent. Do not edit by hand; run: npm run sync:agent\n` +
    `export const AGENT_FILES: Record<string, string> = ${JSON.stringify(files, null, 2)};\n`
);
console.log(`Wrote ${path.relative(process.cwd(), target)} (${FILES.length} files)`);
